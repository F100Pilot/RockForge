"""The PyInstaller spec must bundle everything the standalone .exe serves.

This exists because it already went wrong once: the spec's data list was written
by hand as a single ``("web/index.html", "web")`` entry, and when 4107 lines of
JS were extracted out of index.html into web/app.js the list silently didn't
follow. The shipped .exe served an index.html whose ``<script src="/app.js">``
had nothing behind it, so the whole UI was inert — and nothing in CI could see
it, because nothing ever looked at the spec.

The spec is a plain Python file that only *calls* PyInstaller's builders at the
end, so it can be executed with stubs and its real ``datas`` list inspected.
"""

from __future__ import annotations

from pathlib import Path
from types import SimpleNamespace
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
SPEC = REPO_ROOT / "rockforge.spec"


def _analysis_kwargs() -> dict[str, Any]:
    """Execute rockforge.spec with the PyInstaller builders stubbed out, and
    return the keyword arguments it actually hands to Analysis()."""
    return _spec_calls()[0]


def _spec_calls() -> tuple[dict[str, Any], dict[str, Any]]:
    """The keyword arguments the spec hands to Analysis() and to EXE()."""
    captured: dict[str, Any] = {}
    exe: dict[str, Any] = {}

    def _analysis(*_args: Any, **kwargs: Any) -> SimpleNamespace:
        captured.update(kwargs)
        return SimpleNamespace(pure=[], zipped_data=[], scripts=[], binaries=[], datas=[])

    namespace: dict[str, Any] = {
        "__file__": str(SPEC),
        "Analysis": _analysis,
        "PYZ": lambda *a, **k: None,
        "EXE": lambda *a, **k: exe.update(k),
        "COLLECT": lambda *a, **k: None,
    }
    # The spec resolves its paths relative to the repo root (that is where
    # `pyinstaller rockforge.spec` runs), so evaluate it from there.
    import os

    cwd = os.getcwd()
    try:
        os.chdir(REPO_ROOT)
        exec(compile(SPEC.read_text(encoding="utf-8"), str(SPEC), "exec"), namespace)
    finally:
        os.chdir(cwd)
    return captured, exe


def _run_spec() -> list[tuple[str, str]]:
    """The ``datas`` list the spec hands to Analysis()."""
    return list(_analysis_kwargs()["datas"])


def test_spec_bundles_every_web_file() -> None:
    """Every file under web/ must reach the bundle — not just the ones someone
    remembered to list. Guards the exact regression above: adding a file to web/
    and forgetting the spec must be impossible, not merely unlikely."""
    datas = _run_spec()
    bundled = {Path(src).resolve() for src, _dest in datas}
    web = REPO_ROOT / "web"
    missing = sorted(
        str(f.relative_to(REPO_ROOT))
        for f in web.rglob("*")
        if f.is_file() and f.resolve() not in bundled
    )
    assert not missing, f"web files absent from the PyInstaller bundle: {missing}"


def test_spec_puts_web_files_where_the_server_looks_for_them() -> None:
    """The app resolves a bundled file as ``<_MEIPASS>/web/<name>``, so the spec's
    destination folders have to mirror web/'s own layout — a flat dump would put
    gear art where nothing reads it."""
    datas = _run_spec()
    dest_by_src = {Path(src).resolve(): dest for src, dest in datas}
    web = REPO_ROOT / "web"
    assert dest_by_src[(web / "index.html").resolve()] == "web"
    assert dest_by_src[(web / "app.js").resolve()] == "web"
    for art in (web / "gear_images").glob("*"):
        if art.is_file():
            assert dest_by_src[art.resolve()] == str(Path("web") / "gear_images")


def test_index_html_only_references_bundled_local_assets() -> None:
    """Anything index.html pulls from our own origin has to exist in web/ — the
    check that would have caught the missing app.js at its source."""
    import re

    html = (REPO_ROOT / "web" / "index.html").read_text(encoding="utf-8")
    refs = re.findall(r'(?:src|href)="/([^"?#]+)[^"]*"', html)
    local = [r for r in refs if not r.startswith(("jobs/", "gear-image/"))]
    assert local, "expected index.html to reference at least app.js"
    for ref in local:
        if ref == "i18n-dicts.js":
            # Generated by the server from every web/i18n-<code>.js.
            assert list((REPO_ROOT / "web").glob("i18n-*.js")), "no web/i18n-<code>.js"
            continue
        assert (REPO_ROOT / "web" / ref).is_file(), f"index.html references missing web/{ref}"


def test_spec_bundles_every_ml_runner_at_its_package_path() -> None:
    """The ML runners are the one kind of module another interpreter executes.

    Demucs, WhisperX, Banquet and (since ``_librosa_runner``) librosa all run in
    a subprocess, which is what lets the frozen .exe delegate them to a Python
    that has the packages. But a subprocess runs a FILE, and inside the bundle a
    package's modules live in the archive — so each runner has to be shipped as
    a data file, at the package path ``ml_python.runner_path`` looks in.

    Same failure mode as the web/app.js regression this module was written for:
    nothing at runtime would notice until someone ran the .exe, which CI cannot
    do. The destination is asserted too, because a runner bundled to the wrong
    folder is exactly as broken as one not bundled at all.
    """
    datas = _run_spec()
    bundled = {Path(src).resolve(): dest for src, dest in datas}
    pkg = REPO_ROOT / "src" / "rockforge"
    runners = sorted(
        {*pkg.rglob("_*_runner.py"), *pkg.rglob("_demucs_patcher.py")}
    )
    assert runners, "no ML runners found — has the layout changed?"
    for runner in runners:
        assert runner in bundled, f"{runner.relative_to(REPO_ROOT)} is not bundled"
        expected = Path("rockforge") / runner.relative_to(pkg).parent
        assert Path(bundled[runner]) == expected, runner.name


def test_spec_bundles_the_modules_celery_imports_by_name() -> None:
    """Creating the Celery app imports its fixups and loaders from strings, which
    PyInstaller cannot see. The standalone build still creates that app (the
    in-process worker imports celery_app and calls the tasks directly), and
    without these modules every job died before it started: "No module named
    'celery.fixups'", leaving new projects pending forever in the .exe."""
    from celery.app.base import BUILTIN_FIXUPS
    from celery.loaders import LOADER_ALIASES

    hidden = set(_analysis_kwargs()["hiddenimports"])
    by_name = {ref.split(":")[0] for ref in (*BUILTIN_FIXUPS, *LOADER_ALIASES.values())}
    assert by_name, "precondition: Celery still names modules to import"
    missing = sorted(by_name - hidden)
    assert not missing, f"rockforge.spec does not bundle {missing}"


def test_spec_bundles_every_data_file_of_the_package_at_its_package_path() -> None:
    """The code reads its data files (templates, catalogue, default tones, flat
    models, the lyric atlas) from beside its modules; one left out of the
    bundle breaks the .exe only, at the moment it is needed. The hand-written
    list missed default_tones/*.json, and every .psarc of a project without its
    own tones failed in the .exe."""
    pkg = REPO_ROOT / "src" / "rockforge"
    bundled = {(REPO_ROOT / src).resolve(): dest for src, dest in _run_spec()}
    data = [f for f in pkg.rglob("*")
            if f.is_file() and f.suffix not in (".py", ".pyc") and "__pycache__" not in f.parts]
    assert any(f.name == "default_lead.json" for f in data)
    for f in data:
        want = str(Path("rockforge") / f.relative_to(pkg).parent)
        where = f.relative_to(REPO_ROOT)
        assert bundled.get(f.resolve()) == want, f"{where} is not bundled at {want}"


def test_spec_bundles_what_the_extra_components_install() -> None:
    """The frozen app has no pyproject.toml, so the spec bundles the extras'
    requirement strings for components.py, at the path it reads them from."""
    import json

    datas = _run_spec()
    match = [(src, dest) for src, dest in datas if src.endswith("components_requirements.json")]
    assert match and match[0][1].replace("\\", "/") == "rockforge/infrastructure"
    reqs = json.loads((REPO_ROOT / match[0][0]).read_text(encoding="utf-8"))
    assert any(r.startswith("demucs") for r in reqs)
    assert any(r.startswith("pdf-to-gp5") for r in reqs)
    assert any(dest.replace("\\", "/") == "rockforge/infrastructure/gpimport"
               and src.endswith("_pdf_runner.py") for src, dest in datas)


def test_spec_records_which_build_the_exe_is() -> None:
    """The frozen app has no git: the spec writes the commit and the CI run it
    was made from into the bundle, where build_info.py reads it."""
    import json

    from rockforge import __version__
    from rockforge.build_info import FILE_NAME

    match = [(src, dest) for src, dest in _run_spec() if src.endswith(FILE_NAME)]
    assert match and match[0][1].replace("\\", "/") == "rockforge"
    info = json.loads((REPO_ROOT / match[0][0]).read_text(encoding="utf-8"))
    assert info["version"] == __version__
    assert len(info["commit"]) == 40 and info["build_id"] and info["built_at"]


def test_the_exe_and_the_installer_carry_the_rockforge_icon() -> None:
    """Without it Windows shows PyInstaller's default icon on the window, the
    taskbar and every shortcut."""
    from PIL import Image

    icon = _spec_calls()[1]["icon"]
    assert icon == "assets/rockforge.ico"
    with Image.open(REPO_ROOT / icon) as ico:
        sizes = set(ico.info["sizes"])
    assert {(16, 16), (32, 32), (48, 48), (256, 256)} <= sizes
    iss = (REPO_ROOT / "installer.iss").read_text(encoding="utf-8")
    assert "SetupIconFile=assets\\rockforge.ico" in iss
